export const CATALOGUE_CLUB: Record<Langue, { readonly [K in CleClub]: string }> = { fr: FR, en: EN };

/** Texte « joueur de club » dans une langue donnée, variables `{nom}` remplacées. */
export function traduireClub(l: Langue, cle: CleClub, vars: Record<string, string | number> = {}): string {
  const brut = CATALOGUE_CLUB[l][cle] || FR[cle];
  return brut.replace(/\{(\w+)\}/g, (tout, nom: string) => (nom in vars ? String(vars[nom]) : tout));
}

/** Texte « joueur de club » dans la langue de l'interface. */
export const tk = (cle: CleClub, vars?: Record<string, string | number>): string => traduireClub(langue(), cle, vars);

/** Nombre écrit dans la langue de l'interface (virgule décimale en français) : 1,5 ou 1.5. */
export const nombreClub = (n: number, l: Langue = langue()): string => {
  const arrondi = Math.round(n * 10) / 10;
  return l === 'fr' ? String(arrondi).replace('.', ',') : String(arrondi);
};
