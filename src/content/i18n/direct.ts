export const CATALOGUE_DIRECT: Record<Langue, { readonly [K in CleDirect]: string }> = { fr: FR, en: EN };

/** Texte du direct dans une langue donnée, variables `{nom}` remplacées. */
export function traduireDirect(l: Langue, cle: CleDirect, vars: Record<string, string | number> = {}): string {
  const brut = CATALOGUE_DIRECT[l][cle] || FR[cle];
  return brut.replace(/\{(\w+)\}/g, (tout, nom: string) => (nom in vars ? String(vars[nom]) : tout));
}

/** Texte du direct dans la langue de l'interface. */
export const td = (cle: CleDirect, vars?: Record<string, string | number>): string => traduireDirect(langue(), cle, vars);
