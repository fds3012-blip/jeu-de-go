export const CATALOGUE_SECURITE: Record<Langue, { readonly [K in CleSecurite]: string }> = { fr: FR, en: EN };

/** Texte dans une langue donnée, variables `{nom}` remplacées. */
export function traduireSecurite(l: Langue, cle: CleSecurite, vars: Record<string, string | number> = {}): string {
  const brut = CATALOGUE_SECURITE[l][cle] || FR[cle];
  return brut.replace(/\{(\w+)\}/g, (tout, nom: string) => (nom in vars ? String(vars[nom]) : tout));
}

/** Texte dans la langue de l'interface. */
export const tsec = (cle: CleSecurite, vars?: Record<string, string | number>): string => traduireSecurite(langue(), cle, vars);
