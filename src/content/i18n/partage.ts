export type ClePartage = keyof typeof FR;
export const CATALOGUE_PARTAGE: Record<Langue, { readonly [K in ClePartage]: string }> = { fr: FR, en: EN };

/** Texte du partage dans une langue donnée, variables `{nom}` remplacées. */
export function traduirePartage(l: Langue, cle: ClePartage, vars: Record<string, string | number> = {}): string {
  const brut = CATALOGUE_PARTAGE[l][cle] || FR[cle];
  return brut.replace(/\{(\w+)\}/g, (tout, nom: string) => (nom in vars ? String(vars[nom]) : tout));
}

/** Texte du partage dans la langue de l'interface. */
export const tp = (cle: ClePartage, vars?: Record<string, string | number>): string => traduirePartage(langue(), cle, vars);
